const uint8_t* char_rows(char ch) {
  for (int i = 0; U::FONT_OVERRIDE[i]; i++) {
    if (U::FONT_OVERRIDE[i] == ch) return U::FONT_OVERRIDE_ROWS[i];
  }
  const unsigned c = (unsigned char)ch;
  return PETME128[(c < 32 || c > 127 ? 127 : c) - 32];
}

